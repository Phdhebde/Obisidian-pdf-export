import { readFileSync, writeFileSync } from 'node:fs';

// Advance widths of the bundled fonts, so the generator can tell whether a
// table fits before pdfmake lays it out. Run from the repo root:
//   node scripts/gen-metrics.mjs
//
// Only Basic Latin and Latin-1 are tabled (French text and every IOC fall in
// there); anything else is estimated from the face's widest letter.
const FACES = {
  Liberation: 'LiberationSans-Regular.ttf',
  'Liberation:bold': 'LiberationSans-Bold.ttf',
  LiberationMono: 'LiberationMono-Regular.ttf',
  'LiberationMono:bold': 'LiberationMono-Bold.ttf',
  Archivo: 'ArchivoBlack-Regular.ttf'
};
const RANGES = [[0x20, 0x7e], [0xa0, 0xff]];

function tableOffsets(b) {
  const out = {};
  for (let i = 0; i < b.readUInt16BE(4); i++) {
    const o = 12 + i * 16;
    out[b.toString('latin1', o, o + 4)] = b.readUInt32BE(o + 8);
  }
  return out;
}

/** Glyph id of a code point, from the Windows Unicode cmap (format 4). */
function glyphLookup(b, cmap) {
  let sub = 0;
  for (let i = 0; i < b.readUInt16BE(cmap + 2); i++) {
    const o = cmap + 4 + i * 8;
    if (b.readUInt16BE(o) === 3 && b.readUInt16BE(o + 2) === 1) sub = cmap + b.readUInt32BE(o + 4);
  }
  if (!sub || b.readUInt16BE(sub) !== 4) throw new Error('cmap format 4 not found');
  const segX2 = b.readUInt16BE(sub + 6);
  const endO = sub + 14, startO = endO + segX2 + 2, deltaO = startO + segX2, rangeO = deltaO + segX2;
  return (cp) => {
    for (let i = 0; i < segX2 / 2; i++) {
      if (cp > b.readUInt16BE(endO + i * 2)) continue;
      const start = b.readUInt16BE(startO + i * 2);
      if (cp < start) return 0;
      const delta = b.readInt16BE(deltaO + i * 2);
      const ro = b.readUInt16BE(rangeO + i * 2);
      if (ro === 0) return (cp + delta) & 0xffff;
      const gi = b.readUInt16BE(rangeO + i * 2 + ro + (cp - start) * 2);
      return gi === 0 ? 0 : (gi + delta) & 0xffff;
    }
    return 0;
  };
}

function faceWidths(file) {
  const b = readFileSync(`fonts/${file}`);
  const t = tableOffsets(b);
  const unitsPerEm = b.readUInt16BE(t.head + 18);
  const metrics = b.readUInt16BE(t.hhea + 34);
  const glyph = glyphLookup(b, t.cmap);
  const advance = (gid) => b.readUInt16BE(t.hmtx + Math.min(gid, metrics - 1) * 4);
  const widths = {};
  for (const [lo, hi] of RANGES) {
    for (let cp = lo; cp <= hi; cp++) {
      const gid = glyph(cp);
      if (gid) widths[cp] = Math.round((advance(gid) * 1000) / unitsPerEm);
    }
  }
  return widths;
}

const faces = Object.entries(FACES).map(([key, file]) => {
  const w = faceWidths(file);
  const row = [];
  for (const [lo, hi] of RANGES) for (let cp = lo; cp <= hi; cp++) row.push(w[cp] ?? 0);
  // Unknown characters are taken as wide as the face's `W`, to err on the side
  // of a table that fits.
  return `  '${key}': { fallback: ${w[0x57]}, widths: [${row.join(',')}] }`;
});

writeFileSync('src/fontMetrics.ts', `/*
 * Advance widths of the bundled fonts, in thousandths of an em.
 *
 * Generated by scripts/gen-metrics.mjs from the TTF files in fonts/ — do not
 * edit by hand. \`widths\` runs over U+0020–U+007E then U+00A0–U+00FF; a 0 is a
 * character the face does not have.
 */

export interface FaceMetrics {
  fallback: number;
  widths: number[];
}

export const FACE_METRICS: Record<string, FaceMetrics> = {
${faces.join(',\n')}
};
`);
console.log('src/fontMetrics.ts written for', Object.keys(FACES).join(', '));
