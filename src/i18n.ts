const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en: EN, fr: FR };

let current: Locale = 'en';

/** Pick the locale from a language tag such as Obsidian's (`fr`, `en-GB`…). */
export function setLocale(tag: string | null | undefined): Locale {
  current = String(tag || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
  return current;
}

export function getLocale(): Locale {
  return current;
}

/** The message for `key` in the current locale, placeholders filled in. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const msg = MESSAGES[current][key] ?? EN[key] ?? key;
  if (!vars) return msg;
  return msg.replace(/\{\{(\w+)\}\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
